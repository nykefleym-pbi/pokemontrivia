// Regenerates src/lib/pokemon-data.slim.generated.ts from the full
// pokemon-data.generated.ts roster. Run with:
//   npx vite-node scripts/build-whos-that-pool.mjs
//
// Why this exists: the whos-that Edge Function needs to pick a random
// Pokémon (and validate a typed guess's types) from the WHOLE roster
// server-side — something no other Edge Function in this codebase needs —
// so it's the first one that would otherwise have to bundle the full
// ~195kb generated roster (evolution chains, slugs, etc. it never uses)
// just for id/name/types. This slim projection keeps the server bundle
// small without hand-duplicating the roster.
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { ALL_POKEMON } from "../src/lib/pokemon-data.generated.ts";

const slim = ALL_POKEMON.map((p) => ({ id: p.id, name: p.name, types: p.types }));

const out = `// AUTO-GENERATED by scripts/build-whos-that-pool.mjs from
// pokemon-data.generated.ts. Do not edit — regenerate if the roster changes.
import type { PokeType } from "./pokemon-data.generated";

export interface SlimPokeEntry {
  id: number;
  name: string;
  types: PokeType[];
}

export const ALL_POKEMON_SLIM: SlimPokeEntry[] = ${JSON.stringify(slim)};
`;

writeFileSync(fileURLToPath(new URL("../src/lib/pokemon-data.slim.generated.ts", import.meta.url)), out);
console.log(`Wrote ${slim.length} entries to src/lib/pokemon-data.slim.generated.ts`);
